/**
 * Build-time helper: generates a simplified silhouette path for the African
 * continent from Natural Earth 1:110m data, used by the AHV logo mark.
 *
 * Run with:  node scripts/build-africa-path.mjs
 * Output:    lib/africa-path.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const { feature, merge } = await import("topojson-client");
const { presimplify, simplify, quantile } = await import("topojson-simplify");
const { geoMercator, geoPath } = await import("d3-geo");

// ISO 3166-1 numeric codes for the African continent.
const AFRICA = new Set([
  "012", "024", "204", "072", "854", "108", "132", "120", "140", "148",
  "174", "178", "180", "384", "262", "818", "226", "232", "748", "231",
  "266", "270", "288", "324", "624", "404", "426", "430", "434", "450",
  "454", "466", "478", "480", "504", "508", "516", "562", "566", "646",
  "678", "686", "690", "694", "706", "710", "728", "729", "834", "768",
  "788", "800", "894", "716", "732",
]);

// Madagascar + surrounding small island states we drop for a clean mark.
const DROP = new Set(["450", "174", "678", "690", "226", "232"]);

const topo = JSON.parse(
  readFileSync(
    resolve(root, "node_modules/world-atlas/countries-110m.json"),
    "utf8",
  ),
);

// Simplify in topojson space (preserves shared borders), keeping 8% of points.
const pre = presimplify(topo);
const simplified = simplify(pre, quantile(pre, 0.25));

const collection = feature(simplified, simplified.objects.countries);
const features = collection.features.filter((f) => {
  const id = String(f.id).padStart(3, "0");
  return AFRICA.has(id) && !DROP.has(id);
});

console.log(`African features: ${features.length}`);

// Merge the individual countries into a single dissolved outline so no
// internal borders are drawn — we want the continent silhouette only.
const merged = merge(
  simplified,
  features.map((f) => {
    // Re-locate the geometry in the simplified topology by matching id.
    const id = String(f.id).padStart(3, "0");
    return simplified.objects.countries.geometries.find(
      (g) => String(g.id).padStart(3, "0") === id,
    );
  }),
);

const africa = { type: "Feature", geometry: merged };

// Project to a 400x420 box.
const projection = geoMercator().fitExtent(
  [
    [6, 6],
    [394, 414],
  ],
  africa,
);

const path = geoPath(projection);
const raw = path(africa);

// Split into individual subpaths and drop specks (tiny islands) so the mark
// reads as a clean continent silhouette rather than visual noise.
const MIN_EXTENT = 10; // minimum bounding-box diagonal, in viewBox units

function splitSubpaths(d) {
  const parts = d.match(/M[^M]*/g) ?? [];
  return parts.map((p) => p.trim()).filter(Boolean);
}

function bboxDiagonal(sub) {
  const nums = sub.match(/-?\d+(?:\.\d+)?/g)?.map(Number) ?? [];
  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  for (let i = 0; i + 1 < nums.length; i += 2) {
    const x = nums[i];
    const y = nums[i + 1];
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return Math.hypot(maxX - minX, maxY - minY);
}

const kept = splitSubpaths(raw)
  .filter((sub) => bboxDiagonal(sub) >= MIN_EXTENT)
  .sort((a, b) => bboxDiagonal(b) - bboxDiagonal(a));

console.log(
  `Subpaths: ${splitSubpaths(raw).length} total, ${kept.length} kept`,
);

// Keep proportional precision: round to 1dp then strip trailing ".0".
const compact = kept
  .join(" ")
  .replace(/-?\d+\.\d+/g, (n) => String(Math.round(parseFloat(n) * 10) / 10))
  .replace(/\.0(?=[ ,])/g, "")
  .trim();

console.log(`Path length: ${compact.length} chars`);

mkdirSync(resolve(root, "lib"), { recursive: true });

const out = `// AUTO-GENERATED by scripts/build-africa-path.mjs. Do not edit by hand.
// Silhouette of the African mainland, derived from Natural Earth 1:110m data
// (public domain) and projected into a 400x420 viewBox.
export const AFRICA_VIEWBOX = "0 0 400 420";

export const AFRICA_PATH =
  ${JSON.stringify(compact)};
`;

writeFileSync(resolve(root, "lib/africa-path.ts"), out, "utf8");
console.log("Wrote lib/africa-path.ts");
